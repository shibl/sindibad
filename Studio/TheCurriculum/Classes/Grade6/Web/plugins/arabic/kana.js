import { registerTopic } from '../../core/topics.js';
import { tapword } from '../engines/tapword.js';
import { roles } from '../engines/visuals.js';

const SENTENCES = [
  ['كانَ', 'الجوُّ', 'جميلاً'], ['أصبحَ', 'الطالبُ', 'نشيطاً'], ['صارَ', 'الماءُ', 'بخاراً'],
  ['ليسَ', 'البحرُ', 'هادئاً'], ['ظلَّ', 'الفلاحُ', 'مجتهداً'], ['أمسى', 'الجوُّ', 'بارداً'],
  ['باتَ', 'الطفلُ', 'نائماً'], ['كانَ', 'الهدهدُ', 'حكيماً'], ['أصبحَت', 'السماءُ', 'صافيةً'],
];
const ISM = { ask: 'اسم كان', hint: 'اسم كان (أو أختها) يأتي بعدها مباشرة، وهو مرفوع بالضمة.', explain: 'كان وأخواتها ترفع الاسم.' };
const KHABAR = { ask: 'خبر كان', hint: 'خبر كان يُخبرنا عن الاسم، وهو منصوب، وعلامته غالباً الفتحة أو تنوين الفتح (ـً).', explain: 'كان وأخواتها تنصب الخبر.' };

export const ITEMS = SENTENCES.flatMap(w => [
  { words: w, answer: 1, ...ISM, note: `«${w[1]}» اسم ${w[0]} مرفوع.` },
  { words: w, answer: 2, ...KHABAR, note: `«${w[2]}» خبر ${w[0]} منصوب.` },
]);

registerTopic({
  id: 'arabic-kana', region: 'arabic', order: 4, icon: '🌅',
  title: 'كان وأخواتها', blurb: 'ترفع الاسم وتنصب الخبر',
  learn: [
    {
      title: 'كان تدخل على الجملة الاسمية',
      html: `<p>الجملة الاسمية: «الجوُّ جميلٌ». إذا دخلت عليها <b>كان</b> صار المبتدأ <b>اسمها</b> (مرفوع) والخبر <b>خبرها</b> (منصوب):</p>
             ${roles([['كانَ', 'verb'], ['الجوُّ', 'fael'], ['جميلاً', 'mafool']]).replace('>فاعل<', '>اسم كان<').replace('>مفعول به<', '>خبر كان<')}`,
      say: 'كان ترفع الاسم وتنصب الخبر. احفظ هذه القاعدة الذهبية!',
    },
    {
      title: 'أخوات كان',
      html: `<p class="big">أصبح • أمسى • أضحى • ظلّ • بات • صار • ليس</p><p>كلها تعمل عمل كان: <b>ترفع الاسم وتنصب الخبر</b>.</p>`,
      say: 'انتبه إلى تنوين الفتح في آخر الخبر: جميلاً، نشيطاً، بارداً.',
    },
  ],
  render: tapword({ items: ITEMS, count: 8, intro: 'في كل جملة فعل ناسخ: اضغط على <b>اسمه</b> أو <b>خبره</b>.' }),
});
