abstract class GenerateSharedFonts : DefaultTask() {
    @get:InputDirectory abstract val source: DirectoryProperty
    @get:InputFile abstract val icon: RegularFileProperty
    @get:InputFile abstract val monochrome: RegularFileProperty
    @get:OutputDirectory abstract val output: DirectoryProperty
    @TaskAction fun generate() {
        val fontDir = output.dir("font").get().asFile.apply { mkdirs() }
        source.get().asFile.listFiles().orEmpty().filter { it.extension == "ttf" }.forEach {
            it.copyTo(fontDir.resolve(it.name), overwrite = true)
        }
        val drawable = output.dir("drawable-nodpi").get().asFile.apply { mkdirs() }
        icon.get().asFile.copyTo(drawable.resolve("shared_launcher.png"), overwrite = true)
        monochrome.get().asFile.copyTo(drawable.resolve("shared_monochrome.png"), overwrite = true)
    }
}
val sharedFonts = tasks.register<GenerateSharedFonts>("generateSharedArt") {
    source.set(layout.projectDirectory.dir("../../Shared/Art/fonts"))
    icon.set(layout.projectDirectory.file("../../Shared/Art/runtime/launcher.png"))
    monochrome.set(layout.projectDirectory.file("../../Shared/Art/runtime/png/ships/empty.png"))
    output.set(layout.buildDirectory.dir("generated/sharedArt"))
}
androidComponents.onVariants { variant ->
    variant.sources.res?.addGeneratedSourceDirectory(sharedFonts, GenerateSharedFonts::output)
}
