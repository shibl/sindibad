// Makes worlds/atlas/shapes.ts (then run npm run build for the .js): the country outlines for the globe and the
// maps of the atlas island, from Natural Earth's 1:110m countries (public
// domain), as packaged by world-atlas 2.0.2 (ISC licence).
//
//   npm i --no-save world-atlas@2.0.2 topojson-client@3.1.0
//   node tools/make-world.ts [path/to/countries-110m.json]
//
// The game follows the maps of the Syrian textbook: Palestine is drawn whole
// (Natural Earth's '376' is merged into it), Western Sahara is drawn as part
// of Morocco; Somaliland goes with Somalia, N. Cyprus with Cyprus, Kosovo
// with Serbia, Taiwan with China. Antarctica is left out.
// Coordinates are kept to a tenth of a degree and stored as integers (×10).

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { merge, feature } = require('topojson-client');
const src = process.argv[2] || require.resolve('world-atlas/countries-110m.json');
const topo = JSON.parse(readFileSync(src, 'utf8'));
/** A country in world-atlas's TopoJSON: its ISO numeric id (some have none) and its name. */
interface Geom { id?: string; properties: { name: string } }
const geoms: Geom[] = topo.objects.countries.geometries;

const byName = (n: string) => geoms.find(g => g.properties.name === n);
const groups = new Map<string, Geom[]>();
for (const g of geoms) {
  if (g.properties.name === 'Antarctica') continue;
  groups.set(g.id ?? g.properties.name, [g]);
}
// [into, …merged]
const MERGES = [['275', '376'], ['504', '732'], ['706', 'Somaliland'], ['196', 'N. Cyprus'], ['688', 'Kosovo'], ['156', '158']];
for (const [into, ...rest] of MERGES) {
  for (const r of rest) {
    const g = (geoms.find(x => x.id === r) || byName(r))!;
    groups.get(into)!.push(g);
    groups.delete(r);
  }
}

const q = (v: number) => Math.round(v * 10);
const out: Record<string, number[][]> = {};
for (const [id, list] of groups) {
  const shape = list.length > 1 ? merge(topo, list) : feature(topo, list[0]).geometry;
  const polys = shape.type === 'Polygon' ? [shape.coordinates] : shape.coordinates;
  const rings: number[][] = [];
  for (const poly of polys) for (const ring of poly) {
    const flat: number[] = [];
    let px: number | null = null, py: number | null = null;
    for (const [lon, lat] of ring) { const x = q(lon), y = q(lat); if (x !== px || y !== py) { flat.push(x, y); px = x; py = y; } }
    if (flat.length >= 6) rings.push(flat);
  }
  out[id] = rings;
}

const here = fileURLToPath(new URL('.', import.meta.url));
const body = Object.entries(out).map(([id, rings]) => `  '${id}': ${JSON.stringify(rings)},`).join('\n');
writeFileSync(`${here}../worlds/atlas/shapes.ts`, `// Country outlines for the atlas island's globe and maps: Natural Earth
// 1:110m (public domain), via world-atlas 2.0.2 (ISC). Generated by
// tools/make-world.ts — do not edit by hand. Keys are ISO 3166-1 numeric
// codes; each country is a list of rings, each ring [lon×10, lat×10, …].
// Palestine is drawn whole and Western Sahara as part of Morocco, as in the
// maps of the Syrian textbook (see tools/make-world.ts).

export const SHAPES: Record<string, number[][]> = {
${body}
};
`);
console.log(`shapes.ts: ${Object.keys(out).length} countries`);
