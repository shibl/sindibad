// Draft content, pending review by Syrian educators.
//
// A task is a list of steps. Each step is one action from the tool tray
// (`do`), or several in any order (`do: [...]`), sometimes followed by a
// small choice (`pick`) — the moment where the book's knowledge matters.
//   hint   what the helper says when asked (points to the rule, never the answer)
//   why    the book's fact, said once the step is done (string or per tool)
//   wrong  a special word for a wrong tool at this step
//   stage  how the plants look as soon as the step is done
//   lapse  weeks pass (a quick day–night time-lapse) with this caption;
//          then: how the plants look afterwards (lapse2/then2: a second one)
//   rounds harvest several times (cotton opens from the bottom up)
//   yield  what you collect at the end
// Nothing waits on a real clock: plants grow when you have cared for them.

