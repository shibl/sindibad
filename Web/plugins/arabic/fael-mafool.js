import { registerTopic } from '../../core/topics.js';
import { tapword } from '../engines/tapword.js';
import { roles } from '../engines/visuals.js';

const SENTENCES = [
  ['كتبَ', 'الطالبُ', 'الدرسَ'],
  ['قرأتْ', 'ياسمينةُ', 'القصةَ'],
  ['رفعَ', 'البحّارُ', 'الشراعَ'],
  ['يحبُّ', 'سندبادُ', 'البحرَ'],
  ['أضاءَ', 'المنارُ', 'الطريقَ'],
  ['شربَ', 'العصفورُ', 'الماءَ'],
  ['زرعَ', 'الفلاحُ', 'الزيتونَ'],
  ['فتحَ', 'المعلمُ', 'البابَ'],
  ['رسمَ', 'الطفلُ', 'السفينةَ'],
  ['يقرأُ', 'الهدهدُ', 'الخريطةَ'],
  ['قطفَتْ', 'البنتُ', 'الياسمينَ'],
  ['سقى', 'الولدُ', 'الشجرةَ'],
];

const FAEL = {
  ask: 'الفاعل',
  hint: 'الفاعل هو مَن قام بالفعل. اسأل نفسك: مَن الذي فعل؟ وهو مرفوع، وعلامته غالباً الضمة.',
  explain: 'الفاعل اسم مرفوع يدل على مَن قام بالفعل.',
};
const MAFOOL = {
  ask: 'المفعول به',
  hint: 'المفعول به هو ما وقع عليه الفعل. اسأل: ماذا فعل؟ ومَن؟ وهو منصوب، وعلامته غالباً الفتحة.',
  explain: 'المفعول به اسم منصوب يدل على ما وقع عليه فعل الفاعل.',
};

export const ITEMS = SENTENCES.flatMap(words => [
  { words, answer: 1, ...FAEL, note: `«${words[1]}» فاعل مرفوع بالضمة.` },
  { words, answer: 2, ...MAFOOL, note: `«${words[2]}» مفعول به منصوب بالفتحة.` },
]);

registerTopic({
  id: 'arabic-fael-mafool',
  region: 'arabic',
  order: 1,
  icon: '✍️',
  title: 'الفاعل والمفعول به',
  blurb: 'مَن قام بالفعل؟ وعلى مَن وقع؟',
  learn: [
    {
      title: 'الجملة الفعلية',
      html: `<p>تبدأ الجملة الفعلية بـ<b class="c-verb">فعل</b>، ثم يأتي <b class="c-fael">الفاعل</b> الذي قام بالفعل، ثم <b class="c-mafool">المفعول به</b> الذي وقع عليه الفعل.</p>
             ${roles([['كتبَ', 'verb'], ['الطالبُ', 'fael'], ['الدرسَ', 'mafool']])}`,
      say: 'كل جملة فعلية مثل سفينة: الفعل هو الشراع، والفاعل هو البحّار، والمفعول به هو ما يحمله!',
    },
    {
      title: 'كيف أجد الفاعل؟',
      html: `<p>اسأل: <b>مَن</b> الذي فعل؟ مَن رفع الشراع؟ ← <b class="c-fael">البحّارُ</b>.</p>
             ${roles([['رفعَ', 'verb'], ['البحّارُ', 'fael'], ['الشراعَ', 'mafool']])}
             <p class="tip">الفاعل <b>مرفوع</b>، وعلامته غالباً <b>الضمة</b> ( ـُـ ).</p>`,
      say: 'انظر إلى آخر الكلمة: الضمة على «البحّارُ» تدلّ على أنه مرفوع.',
    },
    {
      title: 'كيف أجد المفعول به؟',
      html: `<p>اسأل: <b>ماذا</b> فعل الفاعل؟ ماذا قرأت ياسمينة؟ ← <b class="c-mafool">القصةَ</b>.</p>
             ${roles([['قرأتْ', 'verb'], ['ياسمينةُ', 'fael'], ['القصةَ', 'mafool']])}
             <p class="tip">المفعول به <b>منصوب</b>، وعلامته غالباً <b>الفتحة</b> ( ـَـ ).</p>`,
      say: 'الآن دورك! سأعرض عليك جملاً، واضغط على الكلمة المطلوبة.',
    },
  ],
  render: tapword({
    items: ITEMS, count: 8,
    intro: 'بوابة الحروف مقفلة بشيفرة! في كل جملة فعلية: <b>فعل</b> ثم <b>فاعل</b> مرفوع ثم <b>مفعول به</b> منصوب.',
  }),
});
