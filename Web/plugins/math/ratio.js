import { registerTopic } from '../../core/topics.js';
import { quiz } from '../engines/quiz.js';
import { num } from '../../core/format.js';

const r = (a, b) => `${num(a)} : ${num(b)}`;
const Q = (q, options, hint, explain) => ({ q, options, answer: 0, hint, explain });
const RATIO = 'النسبة مقارنة بين كميتين بالقسمة. اقسم الحدّين على أكبر عدد يقسمهما معاً لتصل إلى أبسط صورة.';
const PROP = 'في التناسب: جِد قيمة الوحدة الواحدة أولاً، ثم اضرب.';

export const QUESTIONS = [
  Q(`في الصف ${num(12)} بنتاً و${num(8)} أولاد. ما نسبة البنات إلى الأولاد؟`, [r(3, 2), r(2, 3), r(4, 3), r(12, 20)], RATIO, `${r(12, 8)} = ${r(3, 2)} (قسمنا على ${num(4)}).`),
  Q(`ما أبسط صورة للنسبة ${r(5, 15)}؟`, [r(1, 3), r(3, 1), r(1, 5), r(5, 3)], RATIO, `نقسم الحدّين على ${num(5)}: ${r(1, 3)}.`),
  Q(`أيّ نسبة تساوي ${r(2, 3)}؟`, [r(4, 6), r(3, 2), r(4, 5), r(2, 5)], 'اضرب الحدّين في العدد نفسه.', `${r(2, 3)} = ${r(4, 6)} (ضربنا في ${num(2)}).`),
  Q(`في كيس ${num(6)} كرات حمراء و${num(4)} زرقاء. ما نسبة الزرقاء إلى كل الكرات؟`, [r(2, 5), r(2, 3), r(4, 6), r(3, 5)], 'المجموع = الحمراء + الزرقاء.', `${r(4, 10)} = ${r(2, 5)}.`),
  Q(`ثمن ${num(3)} دفاتر ${num(600)} ليرة. كم ثمن ${num(5)} دفاتر؟`, [num(1000), num(900), num(1200), num(800)], PROP, `ثمن الدفتر ${num(200)}، و${num(5)} × ${num(200)} = ${num(1000)}.`),
  Q(`خريطة مقياسها: ${num(1)} سم لكل ${num(10)} كم. المسافة على الخريطة ${num(4)} سم. كم هي في الواقع؟`, [`${num(40)} كم`, `${num(14)} كم`, `${num(4)} كم`, `${num(400)} كم`], PROP, `${num(4)} × ${num(10)} = ${num(40)} كم.`),
  Q(`وصفة تحتاج كوبَي طحين لكل ${num(3)} بيضات. كم كوب طحين لـ${num(9)} بيضات؟`, [num(6), num(3), num(9), num(5)], PROP, `${num(9)} بيضات = ٣ أضعاف، إذن ${num(2)} × ${num(3)} = ${num(6)}.`),
  Q(`سيارة تقطع ${num(120)} كم في ساعتين. كم تقطع في ${num(5)} ساعات بالسرعة نفسها؟`, [`${num(300)} كم`, `${num(250)} كم`, `${num(600)} كم`, `${num(240)} كم`], PROP, `${num(60)} كم في الساعة × ${num(5)} = ${num(300)} كم.`),
];

registerTopic({
  id: 'math-ratio', region: 'math', order: 6, icon: '⚖️',
  title: 'النسبة والتناسب', blurb: 'قارِن واحسب بالتناسب',
  learn: [
    {
      title: 'ما النسبة؟',
      html: `<p>عند الطبّاخة <b>${num(6)}</b> بيضات و<b>${num(3)}</b> أكواب طحين. النسبة: <b>${r(6, 3)} = ${r(2, 1)}</b></p><p class="tip">نقرأ ${r(2, 1)}: «اثنان إلى واحد».</p>`,
      say: 'النسبة تبقى نفسها إذا ضربنا الحدّين أو قسمناهما على العدد نفسه.',
    },
    {
      title: 'التناسب: قيمة الوحدة',
      html: `<p>${num(3)} دفاتر بـ${num(600)} ليرة ← الدفتر الواحد بـ${num(200)} ← ${num(5)} دفاتر بـ<b>${num(1000)}</b></p>`,
      say: 'ابحث دائماً عن قيمة الواحد أولاً.',
    },
  ],
  render: quiz({ questions: QUESTIONS, count: 7, intro: 'مطبخ أم فادي يحتاج حسابات دقيقة! هيّا نحسب بالنسبة والتناسب.' }),
});
