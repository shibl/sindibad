const MEASURE = 'اقرأ الأرقام على حافة الدائرة، وابدأ العدّ من الصفر عند الضلع الثابت.';
const deg = (n) => `${num(n)} درجة`;
const measures = [45, 30, 60, 75, 120, 150].map((a) => ({
    q: `وجّه السفينة بزاوية <b>${deg(a)}</b>.`, angle: a, hint: MEASURE,
    explain: `زاوية ${a < 90 ? 'حادّة' : 'منفرجة'} قياسها ${deg(a)}.`,
}));
const complements = [30, 55, 70].map((a) => ({
    q: `زاويتان <b>متتامّتان</b>، إحداهما ${deg(a)}. كم الأخرى؟`, angle: 90 - a,
    hint: 'الزاويتان المتتامّتان مجموع قياسيهما زاوية قائمة.',
    explain: `${num(90)} − ${num(a)} = ${deg(90 - a)}.`, note: `${num(a)} + ${num(90 - a)} = ${num(90)}`,
}));
const supplements = [70, 135, 40].map((a) => ({
    q: `زاويتان <b>متكاملتان</b>، إحداهما ${deg(a)}. كم الأخرى؟`, angle: 180 - a,
    hint: 'الزاويتان المتكاملتان مجموع قياسيهما زاوية مستقيمة.',
    explain: `${num(180)} − ${num(a)} = ${deg(180 - a)}.`, note: `${num(a)} + ${num(180 - a)} = ${num(180)}`,
}));
/** On the hour: the hand on 12 and the hand on the hour, 30° apart per hour. */
const HOURS = [[3, 'الثالثة'], [2, 'الثانية'], [5, 'الخامسة']];
const clocks = HOURS.map(([h, name]) => ({
    q: `الساعة <b>${name}</b> تماماً: كم الزاوية بين العقربين؟`, angle: h * 30,
    hint: 'دورة الساعة كاملةً 360 درجة، وعليها اثنا عشر رقماً. كم درجة بين كل رقمين متجاورين؟',
    explain: `بين كل رقمين ${deg(30)}، و${num(h)} × ${num(30)} = ${deg(h * 30)}.`,
}));
