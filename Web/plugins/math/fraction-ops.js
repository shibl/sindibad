// Grade 6 Maths — العمليات على الكسور (adding, subtracting, multiplying fractions).
// Draft content, pending review by Syrian educators. CC-BY-SA.
// Distractors are the classic mistakes (adding denominators, etc.) so the
// hints can address them.

import { registerTopic } from '../../core/topics.js';
import { quiz } from '../engines/quiz.js';
import { frac as f } from '../../core/format.js';
import { fracBar } from '../engines/visuals.js';

const Q = (q, options, hint, explain) => ({ q: `${q} = ؟`, options, answer: 0, hint, explain });

const SAME = 'عند تساوي المقامات نجمع (أو نطرح) البسوط فقط ويبقى المقام كما هو.';
const DIFF = 'وحِّد المقامات أولاً: حوّل الكسرين إلى كسرين لهما المقام نفسه، ثم اجمع البسطين.';
const MUL = 'في الضرب: بسط × بسط، ومقام × مقام، ثم اختصر إن أمكن.';

export const QUESTIONS = [
  Q(`${f(2, 7)} + ${f(3, 7)}`, [f(5, 7), f(5, 14), f(6, 7), f(1, 7)], SAME, `${f(2, 7)} + ${f(3, 7)} = ${f(5, 7)}.`),
  Q(`${f(5, 9)} − ${f(2, 9)}`, [f(3, 9), f(7, 9), f(3, 18), f(7, 18)], SAME, `${f(5, 9)} − ${f(2, 9)} = ${f(3, 9)}.`),
  Q(`${f(1, 2)} + ${f(1, 4)}`, [f(3, 4), f(2, 6), f(2, 4), f(1, 8)], DIFF, `${f(1, 2)} = ${f(2, 4)}، و${f(2, 4)} + ${f(1, 4)} = ${f(3, 4)}.`),
  Q(`${f(1, 3)} + ${f(1, 6)}`, [f(1, 2), f(2, 9), f(2, 6), f(1, 18)], DIFF, `${f(1, 3)} = ${f(2, 6)}، و${f(2, 6)} + ${f(1, 6)} = ${f(3, 6)} = ${f(1, 2)}.`),
  Q(`${f(2, 3)} + ${f(1, 6)}`, [f(5, 6), f(3, 9), f(3, 6), f(2, 18)], DIFF, `${f(2, 3)} = ${f(4, 6)}، و${f(4, 6)} + ${f(1, 6)} = ${f(5, 6)}.`),
  Q(`${f(3, 4)} − ${f(1, 2)}`, [f(1, 4), f(2, 2), f(2, 4), f(1, 2)], DIFF, `${f(1, 2)} = ${f(2, 4)}، و${f(3, 4)} − ${f(2, 4)} = ${f(1, 4)}.`),
  Q(`${f(5, 6)} − ${f(1, 3)}`, [f(1, 2), f(4, 3), f(4, 6), f(1, 6)], DIFF, `${f(1, 3)} = ${f(2, 6)}، و${f(5, 6)} − ${f(2, 6)} = ${f(3, 6)} = ${f(1, 2)}.`),
  Q(`${f(2, 5)} + ${f(3, 10)}`, [f(7, 10), f(5, 15), f(5, 10), f(6, 10)], DIFF, `${f(2, 5)} = ${f(4, 10)}، و${f(4, 10)} + ${f(3, 10)} = ${f(7, 10)}.`),
  Q(`${f(2, 3)} × ${f(3, 4)}`, [f(1, 2), f(5, 7), f(6, 7), f(8, 9)], MUL, `${f(2, 3)} × ${f(3, 4)} = ${f(6, 12)} = ${f(1, 2)}.`),
  Q(`${f(1, 2)} × ${f(4, 5)}`, [f(2, 5), f(5, 7), f(4, 7), f(1, 5)], MUL, `${f(1, 2)} × ${f(4, 5)} = ${f(4, 10)} = ${f(2, 5)}.`),
  Q(`${f(3, 5)} × ${f(1, 3)}`, [f(1, 5), f(4, 8), f(3, 8), f(4, 15)], MUL, `${f(3, 5)} × ${f(1, 3)} = ${f(3, 15)} = ${f(1, 5)}.`),
  Q(`${f(1, 4)} + ${f(1, 4)}`, [f(1, 2), f(2, 8), f(1, 8), f(1, 16)], SAME, `${f(1, 4)} + ${f(1, 4)} = ${f(2, 4)} = ${f(1, 2)}.`),
];

registerTopic({
  id: 'math-fraction-ops',
  region: 'math',
  order: 4,
  icon: '➗',
  title: 'العمليات على الكسور',
  blurb: 'جمع وطرح وضرب الكسور',
  learn: [
    {
      title: 'مقامات متساوية',
      html: `<p>${f(2, 7)} + ${f(3, 7)} = ${f(5, 7)} — نجمع <b>البسطين</b> فقط ويبقى المقام.</p>${fracBar(5, 7, '#2f8a5f')}`,
      say: 'الأجزاء من الحجم نفسه، فنعدّها فقط.',
    },
    {
      title: 'مقامات مختلفة',
      html: `<p>${f(1, 2)} + ${f(1, 4)}: نحوّل ${f(1, 2)} = ${f(2, 4)}، ثم ${f(2, 4)} + ${f(1, 4)} = <b>${f(3, 4)}</b></p>
             ${fracBar(2, 4)}${fracBar(3, 4, '#2f8a5f')}
             <p class="tip">⚠️ لا نجمع المقامات أبداً: ${f(1, 2)} + ${f(1, 4)} ≠ ${f(2, 6)}</p>`,
      say: 'أشهر خطأ هو جمع المقامات. لا تقع فيه!',
    },
    {
      title: 'الضرب',
      html: `<p>بسط × بسط، ومقام × مقام، ثم نختصر:</p><p class="big">${f(2, 3)} × ${f(3, 4)} = ${f(6, 12)} = ${f(1, 2)}</p>`,
      say: 'الضرب أسهل مما تظن. هيّا نحسب حمولة السفينة!',
    },
  ],
  render: quiz({
    questions: QUESTIONS, count: 8,
    intro: 'لنحسب حمولة السفينة بالكسور! تذكّر: <b>وحِّد المقامات</b> قبل الجمع والطرح.',
  }),
});
