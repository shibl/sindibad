// The quick review of a quest (plugins/music/): its question steps that
// need no sound or picture, and its extra `review` questions, in the shape
// plugins/engines/quiz.js expects (answer 0 = the first option).
export function reviewOf(id) {
  const q = QUESTS.find(x => x.id === id);
  const fromSteps = q.steps.filter(s => s.kind === 'choice' && !s.listen && !s.art && !s.show);
  return [...fromSteps, ...(q.review || [])].map(({ q: text, options, hint, explain }) => ({ q: text, options, answer: 0, hint, explain }));
}

