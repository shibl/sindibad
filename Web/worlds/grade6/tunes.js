// «جزيرة الأنغام» — the music island: the grade-6 music book
// («التربية الموسيقية»، الصف السادس، 2025–2026) played instead of read.
//
// Each quest is one or more lessons of the book, played at a place on the
// island (the giant piano, the theatre, the drum circle…). A quest is a list
// of steps; core/tunes/games.js draws each kind of step:
//
//   learn    a short card (title, html, optional `show` picture, `play` sound)
//   choice   a question: options[0] is right (shown shuffled); `listen` plays
//            a sound with the question; `art` draws a picture on each option
//   keys     play these notes on the piano, in order (`play`)
//   gaps     tap the two places on the piano with no black key between
//   pattern  mark each step of the C major scale: whole tone or half tone
//   staff    rain drops: put each named note on the grand staff (`drops`)
//   name     a note on the staff: which is it? (options[0] is right)
//   order    tap the items in the right order (`items` is that order)
//   rhythm   hear a rhythm, pick its card (`pattern` is right; `others`)
//   drum     hear a rhythm, then tap it on the drum
//   measure  fill a measure with note values (`beats`, `given`)
//   sort     put each item in its basket (`bins`, `items: [text, bin]`)
//   fill     fill a glass to a fraction (`glass`, `n`/`d`)
//   glasses  play these glasses in order (`play`)
//
// Notes are letters + octave (C4 = «دو الوسطى»); rhythms are tokens:
// q = سوداء (1 beat), h = بيضاء (2), w = مستديرة (4), ee = two ذات السنّ
// (1 beat together), r = a one-beat rest.
//
// Draft content, pending review by Syrian educators. CC-BY-SA.

