import { registerTopic } from '../../core/topics.js';
import { quiz } from '../engines/quiz.js';
import { planets } from '../engines/visuals.js';

const P = ['عطارد', 'الزهرة', 'الأرض', 'المريخ', 'المشتري', 'زحل', 'أورانوس', 'نبتون'];
const Q = (q, ans, hint, explain) => ({
  q, options: [ans, ...P.filter(p => p !== ans).sort(() => Math.random() - 0.5).slice(0, 3)], answer: 0, hint, explain,
});

export const QUESTIONS = [
  Q('☀️ ما أقرب كوكب إلى الشمس؟', 'عطارد', 'إنه أصغر الكواكب وأسرعها دوراناً حول الشمس.', 'عطارد أقرب الكواكب إلى الشمس.'),
  Q('🪐 ما أكبر كواكب المجموعة الشمسية؟', 'المشتري', 'كوكب عملاق غازي فيه بقعة حمراء كبيرة.', 'المشتري أكبر الكواكب.'),
  Q('🔴 أيّ كوكب يُسمّى «الكوكب الأحمر»؟', 'المريخ', 'تربته غنية بأكسيد الحديد فيبدو أحمر.', 'المريخ هو الكوكب الأحمر.'),
  Q('💍 أيّ كوكب تحيط به حلقات جميلة واضحة؟', 'زحل', 'إنه سادس الكواكب بعداً عن الشمس.', 'زحل مشهور بحلقاته.'),
  Q('🌍 على أيّ كوكب نعيش؟', 'الأرض', 'إنه الكوكب الثالث، وفيه ماء وهواء.', 'نعيش على الأرض، ثالث الكواكب.'),
  Q('✨ أيّ كوكب هو ألمع جرم في السماء بعد القمر؟', 'الزهرة', 'يُسمّى أحياناً «نجمة الصباح».', 'الزهرة ألمع الكواكب في سمائنا.'),
  Q('🥶 ما أبعد كوكب عن الشمس؟', 'نبتون', 'إنه أزرق وبارد جداً وهو الثامن.', 'نبتون أبعد الكواكب عن الشمس.'),
  Q('🔢 ما الكوكب الرابع بُعداً عن الشمس؟', 'المريخ', 'عُدّ: عطارد، الزهرة، الأرض، ثم…', 'الترتيب: عطارد، الزهرة، الأرض، المريخ.'),
];

registerTopic({
  id: 'science-planets',
  region: 'science',
  order: 3,
  icon: '🪐',
  title: 'المجموعة الشمسية',
  blurb: 'ثمانية كواكب تدور حول الشمس',
  learn: [
    {
      title: 'ثمانية كواكب',
      html: `${planets()}<p>بالترتيب من الشمس: عطارد، الزهرة، الأرض، المريخ، المشتري، زحل، أورانوس، نبتون.</p>`,
      say: 'نحن نعيش على الكوكب الثالث: الأرض.',
    },
    {
      title: 'حيل للتذكّر',
      html: `<ul class="facts"><li>☀️ <b>عطارد</b> الأقرب إلى الشمس</li><li>🪐 <b>المشتري</b> الأكبر</li><li>🔴 <b>المريخ</b> الكوكب الأحمر</li><li>💍 <b>زحل</b> صاحب الحلقات</li><li>🥶 <b>نبتون</b> الأبعد</li></ul>`,
      say: 'احفظ هذه الخمس جيداً، ستحتاجها بعد قليل!',
    },
  ],
  render: quiz({
    questions: QUESTIONS, count: 7,
    intro: 'البحّارة قديماً اهتدوا بالنجوم! تعرّف إلى <b>الكواكب الثمانية</b> التي تدور حول الشمس.',
  }),
});
