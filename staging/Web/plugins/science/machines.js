import { registerTopic } from '../../core/topics.js';
import { quiz } from '../engines/quiz.js';
import { shuffle } from '../engines/kit.js';

const M = {
  lever: 'الرافعة', pulley: 'البكرة', ramp: 'السطح المائل', wheel: 'العجلة والمحور', wedge: 'الإسفين', screw: 'البرغي (اللولب)',
};
const HINT = {
  lever: 'قضيب يدور حول نقطة ارتكاز.',
  pulley: 'عجلة يمرّ عليها حبل لرفع الأثقال.',
  ramp: 'سطح منحدر يسهّل رفع الأجسام إلى أعلى.',
  wheel: 'عجلة كبيرة مثبّتة على محور صغير يدوران معاً.',
  wedge: 'طرف حادّ رفيع يشقّ الأشياء أو يفصلها.',
  screw: 'سطح مائل ملفوف حول أسطوانة.',
};
const EXAMPLES = [
  ['المقصّ', 'lever'], ['الأرجوحة المتوازنة (السّي سو)', 'lever'], ['فتّاحة الزجاجات', 'lever'],
  ['حبل الدلو فوق البئر', 'pulley'], ['رافعة العلَم على السارية', 'pulley'],
  ['منحدر الكرسي المتحرّك', 'ramp'], ['طريق متعرّج يصعد الجبل', 'ramp'],
  ['مقبض الباب الدائري', 'wheel'], ['مقود الدرّاجة ودولابها', 'wheel'],
  ['السكّين', 'wedge'], ['الفأس', 'wedge'],
  ['غطاء المرطبان', 'screw'], ['مسمار البرغي في الخشب', 'screw'],
];

export const QUESTIONS = [
  ...EXAMPLES.map(([thing, kind]) => ({
    q: `إلى أيّ آلة بسيطة ينتمي: <b>${thing}</b>؟`,
    options: [M[kind], ...shuffle(Object.keys(M).filter(k => k !== kind)).slice(0, 3).map(k => M[k])], answer: 0,
    hint: HINT[kind], explain: `${thing}: ${M[kind]} — ${HINT[kind]}`,
  })),
  { q: 'لماذا نستخدم الآلات البسيطة؟', options: ['لتسهيل العمل وتقليل القوة اللازمة', 'لإنتاج الطاقة من لا شيء', 'لزيادة وزن الأجسام', 'لإيقاف الحركة تماماً'], answer: 0, hint: 'فكّر في المنحدر: هل يصنع طاقة؟', explain: 'الآلة البسيطة تسهّل العمل: نبذل قوة أقل على مسافة أطول، لكنها لا تصنع طاقة.' },
  { q: 'في الرافعة، النقطة التي يدور حولها القضيب تُسمّى:', options: ['نقطة الارتكاز', 'المحور الدوّار', 'رأس الإسفين', 'مركز البكرة'], answer: 0, hint: 'مثل منتصف الأرجوحة المتوازنة.', explain: 'نقطة الارتكاز هي التي يدور حولها قضيب الرافعة.' },
];

registerTopic({
  id: 'science-machines', region: 'science', order: 7, icon: '⚙️',
  title: 'الآلات البسيطة', blurb: 'رافعة، بكرة، منحدر… حولك في كل مكان',
  learn: [
    {
      title: 'ستّ آلات بسيطة',
      html: '<p>⚖️ <b>الرافعة</b> • 🪣 <b>البكرة</b> • ♿ <b>السطح المائل</b></p><p>🚲 <b>العجلة والمحور</b> • 🔪 <b>الإسفين</b> • 🔩 <b>البرغي</b></p>',
      say: 'آلات بلا محرّك، لكنها تجعل العمل أسهل.',
    },
    {
      title: 'قوة أقل… مسافة أطول',
      html: '<p>المنحدر أطول من الدرج، لكن دفع الكرسي عليه أسهل.</p><p class="tip">الآلة البسيطة لا تصنع طاقة؛ إنها توزّع الجهد.</p>',
      say: 'كل آلة بسيطة تبادل القوة بالمسافة.',
    },
  ],
  render: quiz({ questions: QUESTIONS, count: 8, intro: 'مختبر الجزيرة مليء بالأدوات! هل تعرف أيّ آلة بسيطة في كل واحدة؟' }),
});
