    private fun wordQuestions(
        key: String, rows: List<List<String>>, positions: List<Int>,
        names: List<String>, hints: List<String>, explanations: List<String>,
    ) = rows.flatMapIndexed { row, words ->
        positions.mapIndexed { part, position ->
            Question("$key-$row-$part", "اضغط على ${names[part]}", words, listOf(position),
                hints[part], explanations[part])
        }
    }
