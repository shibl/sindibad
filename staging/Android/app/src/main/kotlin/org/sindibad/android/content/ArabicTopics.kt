    private fun sorting(
        key: String, title: String, blurb: String, prompt: String, cards: List<LearnCard>,
        bins: List<String>, rows: List<List<String>>, hints: List<String>, explanations: List<String>,
    ) = Topic("arabic-$key", title, blurb, ActivityKind.Sort, cards,
        rows.flatMapIndexed { bin, words -> words.mapIndexed { i, word ->
            Question("$key-$bin-$i", prompt, bins, listOf(bin), hints[bin], explanations[bin], stimulus = word)
        } }, 9)

